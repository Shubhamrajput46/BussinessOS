"""Single source of truth for who may do what (used by web views, sidebar and the REST API)."""
from apps.accounts.models import User

R = User.Role

OWNER_ADMIN = (R.OWNER, R.ADMIN)
OWNER_ADMIN_MANAGER = (R.OWNER, R.ADMIN, R.MANAGER)
OPERATIONS = (R.OWNER, R.ADMIN, R.MANAGER, R.STAFF)
FINANCE_VIEW = (R.OWNER, R.ADMIN, R.MANAGER, R.ACCOUNTANT)
FINANCE_WRITE = (R.OWNER, R.ADMIN, R.ACCOUNTANT)
EVERYONE = (R.OWNER, R.ADMIN, R.MANAGER, R.STAFF, R.ACCOUNTANT)

# Web (HTML) permission matrix
PRODUCT_WRITE = OWNER_ADMIN_MANAGER
PRODUCT_DELETE = OWNER_ADMIN
CUSTOMER_WRITE = OWNER_ADMIN_MANAGER
CUSTOMER_CREATE = OPERATIONS
ORDER_VIEW = OPERATIONS + (R.ACCOUNTANT,)
ORDER_CREATE = OPERATIONS
ORDER_EDIT = OWNER_ADMIN_MANAGER
INVENTORY = OPERATIONS
EXPENSE_VIEW = FINANCE_VIEW
EXPENSE_WRITE = FINANCE_WRITE
DELETE = OWNER_ADMIN
